//! The Information Schema's queries the explorer reads by
//! (`[DOC sql/07-information-schema.md The views]`), each with its
//! columns in the order the reader takes them, and `?` for the schema or
//! name it is of.

/// The schemas.
pub const SCHEMAS: &str = "SELECT SCHEMA_NAME, SCHEMA_OWNER FROM INFORMATION_SCHEMA.SCHEMATA ORDER BY SCHEMA_NAME";

/// A schema's tables and views.
pub const TABLES: &str = "SELECT TABLE_NAME, TABLE_TYPE FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME";

/// A table's kind.
pub const TABLE_KIND: &str = "SELECT TABLE_TYPE FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ?";

/// A schema's routines.
pub const ROUTINES: &str = "SELECT SPECIFIC_NAME, ROUTINE_NAME, ROUTINE_TYPE FROM INFORMATION_SCHEMA.ROUTINES \
     WHERE ROUTINE_SCHEMA = ? ORDER BY ROUTINE_NAME, SPECIFIC_NAME";

/// A schema's sequence generators.
pub const SEQUENCES: &str = "SELECT SEQUENCE_NAME, DATA_TYPE, NUMERIC_PRECISION, NUMERIC_SCALE, START_VALUE, MINIMUM_VALUE, \
     MAXIMUM_VALUE, INCREMENT, CYCLE_OPTION FROM INFORMATION_SCHEMA.SEQUENCES WHERE SEQUENCE_SCHEMA = ? ORDER BY SEQUENCE_NAME";

/// A schema's domains.
pub const DOMAINS: &str = "SELECT DOMAIN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, DOMAIN_DEFAULT \
     FROM INFORMATION_SCHEMA.DOMAINS WHERE DOMAIN_SCHEMA = ? ORDER BY DOMAIN_NAME";

/// A schema's domains' constraints.
pub const DOMAIN_CHECKS: &str = "SELECT D.DOMAIN_NAME, D.CONSTRAINT_NAME, C.CHECK_CLAUSE FROM INFORMATION_SCHEMA.DOMAIN_CONSTRAINTS D \
     JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS C ON C.CONSTRAINT_SCHEMA = D.CONSTRAINT_SCHEMA AND C.CONSTRAINT_NAME = D.CONSTRAINT_NAME \
     WHERE D.DOMAIN_SCHEMA = ? ORDER BY D.DOMAIN_NAME, D.CONSTRAINT_NAME";

/// A schema's user-defined types.
pub const TYPES: &str = "SELECT USER_DEFINED_TYPE_NAME, USER_DEFINED_TYPE_CATEGORY FROM INFORMATION_SCHEMA.USER_DEFINED_TYPES \
     WHERE USER_DEFINED_TYPE_SCHEMA = ? ORDER BY USER_DEFINED_TYPE_NAME";

/// A table's columns.
pub const COLUMNS: &str = "SELECT COLUMN_NAME, ORDINAL_POSITION, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, \
     COLUMN_DEFAULT, IS_NULLABLE, IS_IDENTITY, IDENTITY_GENERATION, IS_GENERATED, GENERATION_EXPRESSION, DOMAIN_NAME \
     FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION";

/// A table's constraints, with a CHECK's condition and a foreign key's rules.
pub const CONSTRAINTS: &str = "SELECT T.CONSTRAINT_NAME, T.CONSTRAINT_TYPE, T.IS_DEFERRABLE, C.CHECK_CLAUSE, R.MATCH_OPTION, \
     R.UPDATE_RULE, R.DELETE_RULE FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS T \
     LEFT JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS C ON C.CONSTRAINT_SCHEMA = T.CONSTRAINT_SCHEMA AND C.CONSTRAINT_NAME = T.CONSTRAINT_NAME \
     LEFT JOIN INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS R ON R.CONSTRAINT_SCHEMA = T.CONSTRAINT_SCHEMA AND R.CONSTRAINT_NAME = T.CONSTRAINT_NAME \
     WHERE T.TABLE_SCHEMA = ? AND T.TABLE_NAME = ? ORDER BY T.CONSTRAINT_NAME";

/// A table's keys' columns, in order.
pub const KEY_COLUMNS: &str = "SELECT CONSTRAINT_NAME, COLUMN_NAME FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE \
     WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY CONSTRAINT_NAME, ORDINAL_POSITION";

/// The tables and columns a table's foreign keys reference, in order.
pub const REFERENCED: &str = "SELECT R.CONSTRAINT_NAME, K.TABLE_SCHEMA, K.TABLE_NAME, K.COLUMN_NAME \
     FROM INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS R \
     JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS T ON T.CONSTRAINT_SCHEMA = R.CONSTRAINT_SCHEMA AND T.CONSTRAINT_NAME = R.CONSTRAINT_NAME \
     JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE K ON K.CONSTRAINT_SCHEMA = R.UNIQUE_CONSTRAINT_SCHEMA AND K.CONSTRAINT_NAME = R.UNIQUE_CONSTRAINT_NAME \
     WHERE T.TABLE_SCHEMA = ? AND T.TABLE_NAME = ? ORDER BY R.CONSTRAINT_NAME, K.ORDINAL_POSITION";

/// A table's indexes.
pub const INDEXES: &str = "SELECT INDEX_NAME, METHOD_NAME, IS_UNIQUE, COLUMN_NAMES FROM INFORMATION_SCHEMA.INDEXES \
     WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY INDEX_NAME";

/// A table's triggers.
pub const TRIGGERS: &str = "SELECT TRIGGER_SCHEMA, TRIGGER_NAME, EVENT_MANIPULATION, ACTION_TIMING, ACTION_ORIENTATION, \
     ACTION_CONDITION, ACTION_STATEMENT FROM INFORMATION_SCHEMA.TRIGGERS \
     WHERE EVENT_OBJECT_SCHEMA = ? AND EVENT_OBJECT_TABLE = ? ORDER BY TRIGGER_NAME, ACTION_ORDER";

/// The privileges on a table.
pub const PRIVILEGES: &str = "SELECT GRANTOR, GRANTEE, PRIVILEGE_TYPE, IS_GRANTABLE FROM INFORMATION_SCHEMA.TABLE_PRIVILEGES \
     WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY GRANTEE, PRIVILEGE_TYPE";

/// A view's definition.
pub const VIEW: &str = "SELECT VIEW_DEFINITION, CHECK_OPTION FROM INFORMATION_SCHEMA.VIEWS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ?";

/// A routine.
pub const ROUTINE: &str = "SELECT ROUTINE_NAME, ROUTINE_TYPE, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, \
     ROUTINE_DEFINITION, IS_DETERMINISTIC, SQL_DATA_ACCESS FROM INFORMATION_SCHEMA.ROUTINES \
     WHERE SPECIFIC_SCHEMA = ? AND SPECIFIC_NAME = ?";

/// A routine's parameters, its result left out.
pub const PARAMETERS: &str = "SELECT PARAMETER_MODE, PARAMETER_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE \
     FROM INFORMATION_SCHEMA.PARAMETERS WHERE SPECIFIC_SCHEMA = ? AND SPECIFIC_NAME = ? AND IS_RESULT = 'NO' ORDER BY ORDINAL_POSITION";

/// The users.
pub const USERS: &str = "SELECT USER_NAME, IS_OWNER, CREATE_ROLE FROM INFORMATION_SCHEMA.USERS ORDER BY USER_NAME";

/// The roles granted.
pub const ROLES: &str = "SELECT GRANTEE, ROLE_NAME, IS_GRANTABLE FROM INFORMATION_SCHEMA.APPLICABLE_ROLES ORDER BY ROLE_NAME, GRANTEE";

/// The roles enabled.
pub const ENABLED_ROLES: &str = "SELECT ROLE_NAME FROM INFORMATION_SCHEMA.ENABLED_ROLES ORDER BY ROLE_NAME";

/// What a view, routine or trigger of a schema and name reads: kind,
/// schema and name of each table.
pub const USES: &str = "SELECT 'TABLE', TABLE_SCHEMA, TABLE_NAME FROM INFORMATION_SCHEMA.VIEW_TABLE_USAGE WHERE VIEW_SCHEMA = ? AND VIEW_NAME = ? \
     UNION SELECT 'TABLE', TABLE_SCHEMA, TABLE_NAME FROM INFORMATION_SCHEMA.ROUTINE_TABLE_USAGE WHERE SPECIFIC_SCHEMA = ? AND SPECIFIC_NAME = ? \
     UNION SELECT 'TABLE', TABLE_SCHEMA, TABLE_NAME FROM INFORMATION_SCHEMA.TRIGGER_TABLE_USAGE WHERE TRIGGER_SCHEMA = ? AND TRIGGER_NAME = ?";

/// What reads or references a table: kind, schema and name of each.
pub const USED_BY: &str = "SELECT 'VIEW', VIEW_SCHEMA, VIEW_NAME FROM INFORMATION_SCHEMA.VIEW_TABLE_USAGE WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? \
     UNION SELECT 'ROUTINE', SPECIFIC_SCHEMA, SPECIFIC_NAME FROM INFORMATION_SCHEMA.ROUTINE_TABLE_USAGE WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? \
     UNION SELECT 'TRIGGER', TRIGGER_SCHEMA, TRIGGER_NAME FROM INFORMATION_SCHEMA.TRIGGER_TABLE_USAGE WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? \
     UNION SELECT 'CONSTRAINT', C.CONSTRAINT_SCHEMA, C.CONSTRAINT_NAME FROM INFORMATION_SCHEMA.CONSTRAINT_TABLE_USAGE C \
     JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS T ON T.CONSTRAINT_SCHEMA = C.CONSTRAINT_SCHEMA AND T.CONSTRAINT_NAME = C.CONSTRAINT_NAME \
     WHERE C.TABLE_SCHEMA = ? AND C.TABLE_NAME = ? AND T.CONSTRAINT_TYPE = 'FOREIGN KEY' AND NOT (T.TABLE_SCHEMA = ? AND T.TABLE_NAME = ?)";

/// Objects whose names hold a text, in any case: kind, schema and name.
pub const SEARCH_NAMES: &str = "SELECT CASE TABLE_TYPE WHEN 'VIEW' THEN 'VIEW' ELSE 'TABLE' END, TABLE_SCHEMA, TABLE_NAME \
     FROM INFORMATION_SCHEMA.TABLES WHERE POSITION(? IN UPPER(TABLE_NAME)) > 0 \
     UNION SELECT 'ROUTINE', SPECIFIC_SCHEMA, SPECIFIC_NAME FROM INFORMATION_SCHEMA.ROUTINES WHERE POSITION(? IN UPPER(ROUTINE_NAME)) > 0 \
     UNION SELECT 'COLUMN', TABLE_SCHEMA, TABLE_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE POSITION(? IN UPPER(COLUMN_NAME)) > 0 \
     ORDER BY 2, 3";

/// Objects whose definitions hold a text, in any case: views' queries,
/// routines' bodies, triggers' actions and checks' conditions.
pub const SEARCH_DEFINITIONS: &str = "SELECT 'VIEW', TABLE_SCHEMA, TABLE_NAME FROM INFORMATION_SCHEMA.VIEWS \
     WHERE POSITION(? IN UPPER(VIEW_DEFINITION)) > 0 \
     UNION SELECT 'ROUTINE', SPECIFIC_SCHEMA, SPECIFIC_NAME FROM INFORMATION_SCHEMA.ROUTINES WHERE POSITION(? IN UPPER(ROUTINE_DEFINITION)) > 0 \
     UNION SELECT 'TRIGGER', TRIGGER_SCHEMA, TRIGGER_NAME FROM INFORMATION_SCHEMA.TRIGGERS WHERE POSITION(? IN UPPER(ACTION_STATEMENT)) > 0 \
     UNION SELECT 'CONSTRAINT', CONSTRAINT_SCHEMA, CONSTRAINT_NAME FROM INFORMATION_SCHEMA.CHECK_CONSTRAINTS \
     WHERE POSITION(? IN UPPER(CHECK_CLAUSE)) > 0 ORDER BY 2, 3";

/// A partitioned table's strategy and key ([DOC sql/23-partitioning.md The Information Schema]).
pub const PARTITIONED: &str =
    "SELECT STRATEGY, KEY_PARTS FROM INFORMATION_SCHEMA.PARTITIONED_TABLES WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ?";

/// A partitioned table's partitions one level down, each with its bound.
pub const PARTITIONS: &str = "SELECT TABLE_SCHEMA, TABLE_NAME, BOUND, IS_PARTITIONED FROM INFORMATION_SCHEMA.PARTITIONS \
     WHERE PARENT_TABLE_SCHEMA = ? AND PARENT_TABLE_NAME = ? ORDER BY TABLE_SCHEMA, TABLE_NAME";

/// The table a partition is a partition of, and its bound.
pub const PARTITION_OF: &str = "SELECT PARENT_TABLE_SCHEMA, PARENT_TABLE_NAME, BOUND FROM INFORMATION_SCHEMA.PARTITIONS \
     WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ?";

/// The indexes a partitioned table's indexes made on its partitions,
/// each its template's name, its partition and its own name, the first of
/// each template first.
pub const PARTITION_INDEXES: &str = "SELECT TEMPLATE_NAME, PARTITION_SCHEMA, PARTITION_NAME, INDEX_NAME FROM INFORMATION_SCHEMA.PARTITION_INDEXES \
     WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY TEMPLATE_NAME, PARTITION_SCHEMA, PARTITION_NAME";

/// A table's storage: its engine, and each option of it given a value of
/// its own, its name, its value and the kind of value it takes
/// ([DOC appendix/g-table-options.md Appendix G: Table Options *(extension)*]).
pub const TABLE_OPTIONS: &str = "SELECT ENGINE_NAME, OPTION_NAME, OPTION_VALUE, VALUE_KIND, VALUE_SOURCE FROM INFORMATION_SCHEMA.TABLE_OPTIONS \
     WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY OPTION_NAME";

/// The options a table's indexes were given by WITH, each its index's
/// name, its own name, its value and the kind of value it takes.
pub const INDEX_OPTIONS: &str = "SELECT INDEX_NAME, OPTION_NAME, OPTION_VALUE, VALUE_KIND FROM INFORMATION_SCHEMA.INDEX_OPTIONS \
     WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? AND VALUE_SOURCE <> 'DEFAULT' ORDER BY INDEX_NAME, OPTION_NAME";

/// The indexes made on a partition by the indexes of the table it is a partition of.
pub const INDEXES_OF_PARTITION: &str = "SELECT INDEX_NAME FROM INFORMATION_SCHEMA.PARTITION_INDEXES \
     WHERE PARTITION_SCHEMA = ? AND PARTITION_NAME = ?";

/// A user-defined type: its category, whether instantiable and final, and
/// a distinct type's source.
pub const USER_TYPE: &str = "SELECT USER_DEFINED_TYPE_CATEGORY, IS_INSTANTIABLE, IS_FINAL, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, \
     NUMERIC_SCALE, REFERENCE_TYPE FROM INFORMATION_SCHEMA.USER_DEFINED_TYPES WHERE USER_DEFINED_TYPE_SCHEMA = ? AND USER_DEFINED_TYPE_NAME = ?";

/// A structured type's direct supertype.
pub const SUPERTYPE: &str = "SELECT SUPERTYPE_SCHEMA, SUPERTYPE_NAME FROM INFORMATION_SCHEMA.DIRECT_SUPERTYPES \
     WHERE UDT_SCHEMA = ? AND UDT_NAME = ?";

/// A type's method specifications.
pub const METHODS: &str = "SELECT SPECIFIC_NAME, METHOD_NAME, IS_STATIC, IS_OVERRIDING, IS_CONSTRUCTOR, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, \
     NUMERIC_PRECISION, NUMERIC_SCALE, RETURN_UDT_SCHEMA, RETURN_UDT_NAME, SQL_DATA_ACCESS, IS_DETERMINISTIC, IS_NULL_CALL \
     FROM INFORMATION_SCHEMA.METHOD_SPECIFICATIONS WHERE UDT_SCHEMA = ? AND UDT_NAME = ? ORDER BY SPECIFIC_NAME";

/// The parameters of a schema's method specifications, in order.
pub const METHOD_PARAMETERS: &str = "SELECT SPECIFIC_NAME, PARAMETER_MODE, PARAMETER_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, \
     NUMERIC_SCALE FROM INFORMATION_SCHEMA.METHOD_SPECIFICATION_PARAMETERS WHERE SPECIFIC_SCHEMA = ? ORDER BY SPECIFIC_NAME, ORDINAL_POSITION";

/// A structured type's attributes, in order.
pub const ATTRIBUTES: &str = "SELECT ATTRIBUTE_NAME, ATTRIBUTE_DEFAULT, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE \
     FROM INFORMATION_SCHEMA.ATTRIBUTES WHERE UDT_SCHEMA = ? AND UDT_NAME = ? ORDER BY ORDINAL_POSITION";

/// The privileges on a table's columns, each with its column.
pub const COLUMN_PRIVILEGES: &str = "SELECT GRANTOR, GRANTEE, PRIVILEGE_TYPE, IS_GRANTABLE, COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMN_PRIVILEGES \
     WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY COLUMN_NAME, GRANTEE, PRIVILEGE_TYPE";

/// The privileges on a routine, by its specific name.
pub const ROUTINE_PRIVILEGES: &str = "SELECT GRANTOR, GRANTEE, PRIVILEGE_TYPE, IS_GRANTABLE FROM INFORMATION_SCHEMA.ROUTINE_PRIVILEGES \
     WHERE SPECIFIC_SCHEMA = ? AND SPECIFIC_NAME = ? ORDER BY GRANTEE, PRIVILEGE_TYPE";

/// USAGE on a domain or a sequence generator, by its kind.
pub const USAGE_PRIVILEGES: &str = "SELECT GRANTOR, GRANTEE, PRIVILEGE_TYPE, IS_GRANTABLE FROM INFORMATION_SCHEMA.USAGE_PRIVILEGES \
     WHERE OBJECT_SCHEMA = ? AND OBJECT_NAME = ? AND OBJECT_TYPE = ? ORDER BY GRANTEE";

/// The roles the user may grant, revoke and drop.
pub const ADMINISTRABLE_ROLES: &str =
    "SELECT DISTINCT ROLE_NAME FROM INFORMATION_SCHEMA.ADMINISTRABLE_ROLE_AUTHORIZATIONS ORDER BY ROLE_NAME";

/// A schema's property graphs (`[DOC sql/07-information-schema.md The views]`).
pub const GRAPHS: &str = "SELECT PROPERTY_GRAPH_NAME, PROPERTY_GRAPH_MODE FROM INFORMATION_SCHEMA.PROPERTY_GRAPHS \
     WHERE PROPERTY_GRAPH_SCHEMA = ? ORDER BY PROPERTY_GRAPH_NAME";

/// The element tables of a schema's property graphs.
pub const GRAPH_ELEMENTS: &str = "SELECT PROPERTY_GRAPH_NAME, ELEMENT_TABLE_ALIAS, ELEMENT_TABLE_KIND, TABLE_SCHEMA, TABLE_NAME, IS_UNDIRECTED \
     FROM INFORMATION_SCHEMA.PG_ELEMENT_TABLES WHERE PROPERTY_GRAPH_SCHEMA = ? \
     ORDER BY PROPERTY_GRAPH_NAME, ELEMENT_TABLE_KIND DESC, ORDINAL_POSITION";

/// The labels of a schema's property graphs' element tables.
pub const GRAPH_LABELS: &str = "SELECT PROPERTY_GRAPH_NAME, ELEMENT_TABLE_ALIAS, LABEL_NAME FROM INFORMATION_SCHEMA.PG_LABELS \
     WHERE PROPERTY_GRAPH_SCHEMA = ? ORDER BY PROPERTY_GRAPH_NAME, ELEMENT_TABLE_ALIAS, ORDINAL_POSITION";

/// The ends of a schema's property graphs' edge tables, by column.
pub const GRAPH_ENDPOINTS: &str = "SELECT PROPERTY_GRAPH_NAME, EDGE_TABLE_ALIAS, EDGE_END, VERTEX_TABLE_ALIAS, EDGE_COLUMN_NAME, VERTEX_COLUMN_NAME \
     FROM INFORMATION_SCHEMA.PG_EDGE_ENDPOINTS WHERE PROPERTY_GRAPH_SCHEMA = ? \
     ORDER BY PROPERTY_GRAPH_NAME, EDGE_TABLE_ALIAS, EDGE_END, ORDINAL_POSITION";

/// The database's settings, each of its value for the session, where it
/// comes from, its default, when a change takes effect and what it is.
pub const SETTINGS: &str = "SELECT SETTING_NAME, SETTING_VALUE, VALUE_SOURCE, DEFAULT_VALUE, TAKES_EFFECT, DESCRIPTION \
     FROM INFORMATION_SCHEMA.SETTINGS ORDER BY SETTING_NAME";
