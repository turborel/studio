CREATE TABLE STAGING.PRODUCTS (ID INTEGER PRIMARY KEY, NAME VARCHAR(40) NOT NULL, PRICE DECIMAL(9,2) NOT NULL);
-- The orders, the products and the lines between them, as a property
-- graph of a schema of its own, so the shop's model holds its tables alone.
CREATE PROPERTY GRAPH STAGING.SHOP
  VERTEX TABLES (DEMO.ORDERS, DEMO.PRODUCTS)
  EDGE TABLES (DEMO.ORDER_LINES SOURCE ORDERS DESTINATION PRODUCTS);
