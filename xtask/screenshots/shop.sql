-- The demo shop's schema as a team designs it next, for Import DDL into
-- Model (RULES.md D60, D64): customers with an e-mail address, and
-- suppliers of the products. Made-up names alone.
CREATE TABLE CUSTOMERS (
  ID INTEGER PRIMARY KEY,
  NAME VARCHAR(40) NOT NULL,
  CITY VARCHAR(30),
  EMAIL VARCHAR(80),
  JOINED DATE NOT NULL
);
CREATE TABLE SUPPLIERS (
  ID INTEGER PRIMARY KEY,
  NAME VARCHAR(40) NOT NULL,
  CITY VARCHAR(30)
);
CREATE TABLE PRODUCTS (
  ID INTEGER PRIMARY KEY,
  NAME VARCHAR(40) NOT NULL,
  PRICE DECIMAL(9,2) NOT NULL CHECK (PRICE > 0),
  SUPPLIER_ID INTEGER REFERENCES SUPPLIERS (ID)
);
CREATE TABLE ORDERS (
  ID INTEGER PRIMARY KEY,
  CUSTOMER_ID INTEGER NOT NULL REFERENCES CUSTOMERS (ID),
  PLACED DATE NOT NULL,
  TOTAL DECIMAL(11,2) NOT NULL
);
CREATE VIEW BIG_ORDERS AS SELECT * FROM ORDERS WHERE TOTAL > 300;
